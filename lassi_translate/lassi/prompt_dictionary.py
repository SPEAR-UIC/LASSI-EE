    def load_context_file(self, filepath):
        """Load a markdown context file from the lassi/context/ directory."""
        full_path = os.path.join(os.path.dirname(__file__), "context", filepath)
        try:
            with open(full_path, "r", encoding="utf-8") as f:
                return f.read()
        except FileNotFoundError:
            print(f"Warning: context file {filepath} not found.")
            return ""
